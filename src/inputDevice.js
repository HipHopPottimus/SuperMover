/**
 * @interface InputDevice
 */

/**
 * @property {number} x - 0-255 horizontal position
 * @memberof InputDevice.prototype
 */

/**
 * @property {number} y - 0-255 vertical position
 * @memberof InputDevice.prototype
 */

/**
 * @property {number} zoom - 0-255 zoom position
 * @memberof InputDevice.prototype
 */

/**
 * @property {number} zoomVelocity - Zoom movement speed
 * @memberof InputDevice.prototype
 */

/**
 * @property {number} dimmer - 0-255 dimmer/throttle position
 * @memberof InputDevice.prototype
 */

/**
 * @property {number} dimmerVelocity - Dimmer movement speed
 * @memberof InputDevice.prototype
 */

/**
 * @property {Function} [onUpdate] - Callback function triggered when values change
 * @memberof InputDevice.prototype
 */